export const ICON_NAMES = Object.freeze(Object.keys(SEMANTIC))

export function Icon({ name, size, color = colors.text, style }) {
  const glyph = SEMANTIC[name] || name
  const xml = ICONS[glyph]
  if (!xml) {
    if (__DEV__) console.warn(`Icon "${name}" missing - run node tools/gen-icons.mjs`)
    return null
  }
  const px = size ?? (SEMANTIC[name] ? 16 : 20)
  return <SvgXml xml={xml} width={px} height={px} color={color} style={style} />
}
