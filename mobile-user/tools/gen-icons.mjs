// Dev-time generator: scans the web app's buyer sources for react-icons imports and writes
// src/components/ui/iconData.js (name -> SVG markup). react-icons has no React Native build, so the
// exact same glyphs are rendered to SVG once here and drawn at runtime with react-native-svg.
// Re-run after porting new screens:  node tools/gen-icons.mjs
import { createRequire } from 'node:module'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
const WEB = 'C:/Users/admin/Documents/GitHub/Krozenda-Dropshiping/frontend'
const require = createRequire(WEB + '/package.json')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const roots = ['src/modules/user', 'src/modules/auth', 'src/components', 'src/lib', 'src/pages'].map((p) => join(WEB, p))
const files = []
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : /\.jsx?$/.test(f) && files.push(p) } }
roots.forEach((r) => { try { walk(r) } catch {} })
const names = new Map() // name -> pkg
const re = /import\s*\{([^}]*)\}\s*from\s*'react-icons\/([a-z0-9]+)'/g
for (const f of files) {
  const src = readFileSync(f, 'utf8'); let m
  while ((m = re.exec(src))) for (const n of m[1].split(',').map((s) => s.trim().split(/\s+as\s+/)[0]).filter(Boolean)) names.set(n, m[2])
}
// Also scan the mobile source for extra names used directly (e.g. <Icon name="HiXMark" />)
const mobileFiles = []
const walk2 = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk2(p) : /\.jsx?$/.test(f) && mobileFiles.push(p) } }
walk2('src')
for (const f of mobileFiles) {
  if (f.endsWith('iconData.js')) continue
  const src = readFileSync(f, 'utf8')
  for (const m of src.matchAll(/\b(Hi|Fa|Fi)[A-Z0-9][A-Za-z0-9]+\b/g)) {
    const n = m[0]; if (names.has(n)) continue
    for (const pkg of ['hi2', 'fa6', 'fi', 'fa']) { try { if (require('react-icons/' + pkg)[n]) { names.set(n, pkg); break } } catch {} }
  }
}
const out = {}
for (const [n, pkg] of [...names].sort()) {
  const C = require('react-icons/' + pkg)[n]
  if (!C) { console.warn('missing', n, pkg); continue }
  out[n] = renderToStaticMarkup(React.createElement(C)).replace(/ class="[^"]*"/g, '')
}
writeFileSync('src/components/ui/iconData.js', `// Generated by tools/gen-icons.mjs — do not edit.\nexport const ICONS = ${JSON.stringify(out, null, 1)}\n`)
console.log(Object.keys(out).length, 'icons')
